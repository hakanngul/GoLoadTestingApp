// Package store persists tests, runs and metrics.
//
// CONTRACT FILE (interface). Implementations: postgres.go (pgx) and
// memory.go (tests and `serve -db memory`).
package store

import (
	"context"
	"errors"

	"github.com/hakanngul/GoLoadTestingApp/internal/model"
)

// ErrNotFound is returned when an entity does not exist.
var ErrNotFound = errors.New("store: not found")

// ErrConflict is returned on unique violations (e.g. duplicate test name).
var ErrConflict = errors.New("store: conflict")

// RunFilter narrows ListRuns. Zero value = all runs, newest first, limit 50.
type RunFilter struct {
	TestID string
	Limit  int
}

// Store is safe for concurrent use. IDs are generated by the store
// (UUIDv4 strings) on Create*. Timestamps are set by the store.
type Store interface {
	ListTests(ctx context.Context) ([]model.Test, error) // newest updated first, LastRun filled
	GetTest(ctx context.Context, id string) (model.Test, error)
	CreateTest(ctx context.Context, t model.Test) (model.Test, error)
	UpdateTest(ctx context.Context, t model.Test) (model.Test, error) // name, yaml
	DeleteTest(ctx context.Context, id string) error                  // cascades runs, files

	PutFile(ctx context.Context, testID, name string, content []byte) error // upsert
	GetFile(ctx context.Context, testID, name string) ([]byte, error)
	DeleteFile(ctx context.Context, testID, name string) error

	CreateRun(ctx context.Context, r model.Run) (model.Run, error)
	UpdateRun(ctx context.Context, r model.Run) error // full replace except ID/TestID
	GetRun(ctx context.Context, id string) (model.Run, error)
	ListRuns(ctx context.Context, f RunFilter) ([]model.Run, error) // newest first
	// MarkInterrupted sets every queued/running run to error with msg
	// (called on master start: runs cannot survive a restart).
	MarkInterrupted(ctx context.Context, msg string) (int, error)

	// AppendMetric stores one per-second point plus the encoded
	// metrics.Snapshot (HDR histograms) for exact re-aggregation later.
	AppendMetric(ctx context.Context, runID string, p model.MetricPoint, snapshot []byte) error
	ListMetrics(ctx context.Context, runID string) ([]model.MetricPoint, error) // ordered by T
	ListSnapshots(ctx context.Context, runID string) ([][]byte, error)

	AppendErrorSamples(ctx context.Context, runID string, s []model.ErrorSample) error
	ListErrorSamples(ctx context.Context, runID string) ([]model.ErrorSample, error)

	Close()
}
