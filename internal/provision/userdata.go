package provision

import (
	"bytes"
	"encoding/base64"
	"errors"
	"fmt"
	"net"
	"regexp"
	"strconv"
	"text/template"
	"time"
)

// workerUserData is the cloud-init shell script every AWS worker boots with.
//
// User data passed to RunInstances replaces the launch template's user data,
// so this script is self-contained: kernel tuning, Docker install, worker
// start, and a hard lifetime limit. Keep it in sync with
// deploy/aws/templates/worker-user-data.sh.tftpl (used for manual launches).
//
// The token is written only to a root-only env file via a quoted heredoc
// (no shell expansion) and handed to Docker with --env-file, so it never
// shows up in the process list or in cloud-init's command echo.
var workerUserData = template.Must(template.New("worker").Parse(`#!/bin/bash
# goload worker bootstrap (generated by internal/provision). Run: {{.RunID}}
set -euo pipefail

# --- hard lifetime: the instance terminates itself even if the master dies.
# (InstanceInitiatedShutdownBehavior=terminate is set at launch.)
shutdown -h +{{.LifetimeMinutes}} "goload worker max lifetime reached" || true

# --- kernel tuning for many concurrent outbound connections
cat > /etc/sysctl.d/99-goload.conf <<'SYSCTL'
fs.file-max = 2097152
fs.nr_open = 2097152
net.ipv4.ip_local_port_range = 1024 65535
net.ipv4.tcp_tw_reuse = 1
net.ipv4.tcp_fin_timeout = 15
net.core.somaxconn = 65535
net.core.netdev_max_backlog = 65535
net.ipv4.tcp_max_syn_backlog = 65535
SYSCTL
sysctl --system >/dev/null
ulimit -n 1048576 || true
cat > /etc/security/limits.d/99-goload.conf <<'LIMITS'
*    soft nofile 1048576
*    hard nofile 1048576
root soft nofile 1048576
root hard nofile 1048576
LIMITS

# --- Docker
if ! command -v docker >/dev/null 2>&1; then
  dnf install -y docker
fi
mkdir -p /etc/systemd/system/docker.service.d
cat > /etc/systemd/system/docker.service.d/limits.conf <<'UNIT'
[Service]
LimitNOFILE=1048576
UNIT
systemctl daemon-reload
systemctl enable --now docker

# --- worker secrets (root only, never echoed)
install -d -m 0700 /etc/goload
umask 077
cat > /etc/goload/worker.env <<'ENV'
GOLOAD_WORKER_TOKEN={{.Token}}
GOLOAD_RUN_ID={{.RunID}}
ENV
chmod 0600 /etc/goload/worker.env

# --- start the worker; host networking avoids Docker NAT overhead.
{{- if .ECRRegistry}}
# Private ECR image: log in with the instance role (needs ECR read access).
aws ecr get-login-password --region {{.ECRRegion}} | docker login --username AWS --password-stdin {{.ECRRegistry}}
{{- end}}
docker pull {{.Image}}
docker run -d --name goload-worker \
  --restart on-failure:5 \
  --network host \
  --ulimit nofile=1048576:1048576 \
  --env-file /etc/goload/worker.env \
  {{.Image}} worker -master {{.MasterAddr}}
`))

type userDataParams struct {
	RunID           string
	MasterAddr      string
	Token           string
	Image           string
	LifetimeMinutes int
	// ECRRegistry / ECRRegion are derived from Image when it lives in ECR.
	ECRRegistry string
	ECRRegion   string
}

var (
	// safeRunID keeps the run id usable in tags, comments and env files.
	safeRunID = regexp.MustCompile(`^[A-Za-z0-9._:-]{1,128}$`)
	// safeImage is a conservative container image reference.
	safeImage = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._/:@-]{0,254}$`)
	// safeHost is a DNS name or IPv4 literal.
	safeHost = regexp.MustCompile(`^[A-Za-z0-9]([A-Za-z0-9.-]{0,252}[A-Za-z0-9])?$`)
	// ecrImage matches private ECR references, capturing registry and region.
	ecrImage = regexp.MustCompile(`^([0-9]{12}\.dkr\.ecr\.([a-z0-9-]+)\.amazonaws\.com(?:\.cn)?)/`)
)

// renderUserData builds the base64-encoded user data for a worker. Every
// value interpolated into the script is validated first so that nothing can
// break out of the script (shell injection via run id, address or token).
func renderUserData(p userDataParams) (string, error) {
	if !safeRunID.MatchString(p.RunID) {
		return "", fmt.Errorf("provision: run id %q has unsupported characters", p.RunID)
	}
	if err := validateMasterAddr(p.MasterAddr); err != nil {
		return "", err
	}
	if err := validateToken(p.Token); err != nil {
		return "", err
	}
	if !safeImage.MatchString(p.Image) {
		return "", fmt.Errorf("provision: worker image %q is not a valid image reference", p.Image)
	}
	if m := ecrImage.FindStringSubmatch(p.Image); m != nil {
		p.ECRRegistry, p.ECRRegion = m[1], m[2]
	}
	if p.LifetimeMinutes < 1 {
		return "", errors.New("provision: worker lifetime must be at least one minute")
	}
	var buf bytes.Buffer
	if err := workerUserData.Execute(&buf, p); err != nil {
		return "", fmt.Errorf("provision: render user data: %w", err)
	}
	// EC2 limits user data to 16 KiB before base64 encoding.
	if buf.Len() > 16*1024 {
		return "", fmt.Errorf("provision: user data is %d bytes, EC2 limit is 16384", buf.Len())
	}
	return base64.StdEncoding.EncodeToString(buf.Bytes()), nil
}

func validateMasterAddr(addr string) error {
	host, port, err := net.SplitHostPort(addr)
	if err != nil {
		return fmt.Errorf("provision: master address %q must be host:port: %w", addr, err)
	}
	if !safeHost.MatchString(host) {
		return fmt.Errorf("provision: master host %q is not a DNS name or IPv4 address", host)
	}
	if n, err := strconv.Atoi(port); err != nil || n < 1 || n > 65535 {
		return fmt.Errorf("provision: master port %q is invalid", port)
	}
	return nil
}

// validateToken rejects tokens that cannot be written safely to a Docker
// env file: they must be printable ASCII without whitespace. The token
// itself is never included in the error.
func validateToken(tok string) error {
	if tok == "" {
		return errors.New("provision: worker token is empty")
	}
	if len(tok) > 1024 {
		return errors.New("provision: worker token is longer than 1024 bytes")
	}
	for i := 0; i < len(tok); i++ {
		if c := tok[i]; c <= ' ' || c > '~' {
			return errors.New("provision: worker token must be printable ASCII without whitespace")
		}
	}
	return nil
}

// lifetimeMinutes rounds d up to whole minutes for shutdown(8).
func lifetimeMinutes(d time.Duration) int {
	return int((d + time.Minute - 1) / time.Minute)
}
